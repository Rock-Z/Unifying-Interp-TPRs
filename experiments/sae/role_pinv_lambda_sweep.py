"""
Sweep role unbinding l2 lambda and plot R^2.
"""
import argparse
import json
import subprocess
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

TITLE_FONTSIZE = 9
LABEL_FONTSIZE = 8
TICK_FONTSIZE = 7


def run_command(command: list[str]) -> None:
    result = subprocess.run(command, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"Command failed: {' '.join(command)}")


def load_r2(metrics_path: Path) -> float:
    metrics = json.loads(metrics_path.read_text())
    return float(metrics["r2"])


def plot_sweep(lambdas: np.ndarray, r2s: np.ndarray, output_path: Path, note: str) -> None:
    fig, ax = plt.subplots(figsize=(6.75, 3.2))
    ax.plot(lambdas, r2s * 100.0, marker="o", linewidth=1.2, color="#0072B2")
    ax.set_xscale("log")
    ax.set_xlabel("Role unbinding l2 lambda", fontsize=LABEL_FONTSIZE)
    ax.set_ylabel(r"$R^2$ (\%)", fontsize=LABEL_FONTSIZE)
    ax.tick_params(axis="both", labelsize=TICK_FONTSIZE, width=0.5, length=2)
    ax.grid(True, alpha=0.3, linewidth=0.3)
    ax.set_axisbelow(True)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.set_title("ModernBERT TPE SAE: Role Unbinding Sweep", fontsize=TITLE_FONTSIZE, pad=6)

    ax.text(
        0.98,
        0.02,
        note,
        transform=ax.transAxes,
        ha="right",
        va="bottom",
        fontsize=6.5,
        bbox={"boxstyle": "round,pad=0.25", "fc": "white", "ec": "0.8", "alpha": 0.9},
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path.with_suffix(".png"), dpi=300, bbox_inches="tight")
    fig.savefig(output_path.with_suffix(".pdf"), bbox_inches="tight")
    print(f"[INFO] Saved plot to {output_path.with_suffix('.png')} and {output_path.with_suffix('.pdf')}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Sweep role unbinding l2 lambda for TPE SAE.")
    parser.add_argument(
        "--gin-file",
        default="experiments/sae/configs/tpr_sae_modernbert.gin",
        help="Gin config for the TPE SAE construction.",
    )
    parser.add_argument(
        "--output-root",
        default="experiments/sae/results/modernbert_role_pinv_lambda_sweep",
        help="Root directory for sweep outputs.",
    )
    parser.add_argument(
        "--lambdas",
        default="1e-4,3e-4,1e-3,3e-3,1e-2,3e-2,1e-1,3e-1,1e0",
        help="Comma-separated list of lambda values.",
    )
    parser.add_argument(
        "--output-plot",
        default="experiments/sae/figures/modernbert_role_pinv_lambda_sweep",
        help="Output path (without extension) for plot files.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    lambdas = np.array([float(val) for val in args.lambdas.split(",")], dtype=float)
    output_root = Path(args.output_root)
    r2s = []

    for lam in lambdas:
        run_dir = output_root / f"lambda_{lam:g}"
        metrics_path = run_dir / "metrics.json"
        command = [
            "uv",
            "run",
            "src/tpr_sae.py",
            args.gin_file,
            f"--main.role_pinv_regularization='l2'",
            f"--main.role_pinv_l2_lambda={lam}",
            f"--main.sae_output_dir='{run_dir.as_posix()}'",
        ]
        run_command(command)
        r2s.append(load_r2(metrics_path))

    r2s = np.array(r2s, dtype=float)
    note = "Generated by sweeping main.role_pinv_l2_lambda\nwith src/tpr_sae.py (ModernBERT)."
    plot_sweep(lambdas, r2s, Path(args.output_plot), note)


if __name__ == "__main__":
    main()
